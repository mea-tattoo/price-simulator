'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'config.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'src/engine.cjs'), 'utf8').replace(/\r\n/g, '\n');
const exportLine = "module.exports = createPricingEngine(require('../config.json'));";
if (!source.trimEnd().endsWith(exportLine)) throw new Error('Unexpected engine export: update build adapter explicitly');
const factorySource = source.slice(0, source.lastIndexOf(exportLine)).trimEnd();
const output = `/* Mea Tattoo Pricing Core ${config.version}; API ${config.apiVersion}. Generated by scripts/build.cjs. */\n`
  + `(function (root, factory) {\n`
  + `  if (typeof module === 'object' && module.exports) module.exports = factory();\n`
  + `  else if (typeof define === 'function' && define.amd) define([], factory);\n`
  + `  else root.MeaPricing = factory();\n`
  + `}(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n`
  + `${factorySource}\n\n`
  + `  return createPricingEngine(${JSON.stringify(config, null, 2)});\n`
  + `}));\n`;
const manifest = {
  apiVersion: config.apiVersion,
  version: config.version,
  file: 'pricing.js',
  sha256: crypto.createHash('sha256').update(output).digest('hex')
};
const dist = path.join(root, 'dist');
fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(path.join(dist, 'pricing.js'), output);
fs.writeFileSync(path.join(dist, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Built dist/pricing.js (${manifest.version}, API ${manifest.apiVersion}, sha256 ${manifest.sha256})`);
